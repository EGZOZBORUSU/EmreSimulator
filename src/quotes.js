const lastQuotesHistory = [];
const lastAuthorsHistory = [];

export function getRandomQuoteInstance(customList = null, selectedCategory = "all") {
  let pool = customList && customList.length > 0 ? customList : RAW_QUOTES;
  
  if (selectedCategory && selectedCategory !== "all") {
    pool = pool.filter(q => q.category === selectedCategory);
    if (pool.length === 0) pool = RAW_QUOTES;
  }

  let availableQuotes = pool.filter(q => !lastQuotesHistory.includes(q.id));
  if (availableQuotes.length === 0) {
    lastQuotesHistory.length = 0;
    availableQuotes = pool;
  }
  
  const chosenQuote = availableQuotes[Math.floor(Math.random() * availableQuotes.length)];
  lastQuotesHistory.push(chosenQuote.id);
  if (lastQuotesHistory.length > 15) lastQuotesHistory.shift();

  // Author assignment
  let authorObj;
  if (chosenQuote.customAuthor) {
    authorObj = {
      name: chosenQuote.customAuthor,
      title: chosenQuote.customTitle,
      image: chosenQuote.customImage,
      authorAudio: null
    };
  } else {
    let availableAuthors = AUTHORS.filter(a => !lastAuthorsHistory.includes(a.name));
    if (availableAuthors.length === 0) {
      lastAuthorsHistory.length = 0;
      availableAuthors = AUTHORS;
    }
    authorObj = availableAuthors[Math.floor(Math.random() * availableAuthors.length)];
    lastAuthorsHistory.push(authorObj.name);
    if (lastAuthorsHistory.length > 2) lastAuthorsHistory.shift();
  }

  // Pick random title
  const randomTitle = chosenQuote.customTitle || authorObj.titles[Math.floor(Math.random() * authorObj.titles.length)];
  const randomYear = String(Math.floor(Math.random() * 3) + 2022); // 2022 - 2024

  return {
    id: chosenQuote.id,
    text: chosenQuote.text,
    category: chosenQuote.category || "felsefi",
    author: authorObj.name,
    title: randomTitle,
    image: chosenQuote.customImage || authorObj.image,
    audio: `/audio/quotes/${chosenQuote.id}.mp3`,
    authorAudio: authorObj.authorAudio || null,
    year: randomYear
  };
}
